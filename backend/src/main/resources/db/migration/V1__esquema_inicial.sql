CREATE TABLE franja_horaria (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mancomunidad_id BIGINT NOT NULL,
    horario_profesor_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    dia_semana TINYINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    aula VARCHAR(100) NULL,
    creado_por BIGINT NOT NULL,
    actualizado_por BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_franja_horaria_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_franja_horaria_horas CHECK (hora_fin > hora_inicio),
    KEY idx_franja_horario (mancomunidad_id, horario_profesor_id, dia_semana),
    KEY idx_franja_asignatura (mancomunidad_id, asignatura_id),
    CONSTRAINT fk_franja_horaria_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id),
    CONSTRAINT fk_franja_horaria_horario FOREIGN KEY (horario_profesor_id) REFERENCES horario_profesor (id),
    CONSTRAINT fk_franja_horaria_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignatura (id),
    CONSTRAINT fk_franja_horaria_creado FOREIGN KEY (creado_por) REFERENCES usuario (id),
    CONSTRAINT fk_franja_horaria_actualizado FOREIGN KEY (actualizado_por) REFERENCES usuario (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE sustitucion (
