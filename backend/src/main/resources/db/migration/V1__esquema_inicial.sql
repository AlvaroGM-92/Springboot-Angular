    KEY idx_historial_usuario (mancomunidad_id, cambiado_por, cambiado_at),
    CONSTRAINT fk_historial_asistencia_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id),
    CONSTRAINT fk_historial_asistencia_asistencia FOREIGN KEY (asistencia_id) REFERENCES asistencia (id),
    CONSTRAINT fk_historial_asistencia_usuario FOREIGN KEY (cambiado_por) REFERENCES usuario (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

