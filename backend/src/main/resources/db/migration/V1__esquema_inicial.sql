-- Esquema inicial de la aplicación.
-- Motor: MySQL 8.4 LTS. Todas las tablas usan utf8mb4.
-- Las tablas editables llevan version para el bloqueo optimista.

CREATE TABLE mancomunidad (
    id BIGINT NOT NULL AUTO_INCREMENT,
    nombre VARCHAR(150) NOT NULL,
    codigo VARCHAR(30) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    duracion_maxima_franja_min INT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_mancomunidad_nombre UNIQUE (nombre),
    CONSTRAINT uq_mancomunidad_codigo UNIQUE (codigo),
    CONSTRAINT ck_mancomunidad_tipo CHECK (tipo IN ('MUSICA', 'DANZA', 'ARTES_ESCENICAS', 'IDIOMAS', 'DEPORTES', 'OTRO')),
    KEY idx_mancomunidad_activo (activo)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE usuario (
    id BIGINT NOT NULL AUTO_INCREMENT,
    nombre VARCHAR(100) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    debe_cambiar_password BOOLEAN NOT NULL DEFAULT FALSE,
    password_temporal_expira_at DATETIME(6) NULL,
    email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
    email_verificado_at DATETIME(6) NULL,
    token_version BIGINT NOT NULL DEFAULT 0,
    admin_plataforma BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_acceso DATETIME(6) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    KEY idx_usuario_activo (activo)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE usuario_mancomunidad (
    id BIGINT NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT NOT NULL,
    mancomunidad_id BIGINT NOT NULL,
    rol VARCHAR(20) NOT NULL,
    token_version BIGINT NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_usuario_mancomunidad UNIQUE (usuario_id, mancomunidad_id),
    CONSTRAINT ck_usuario_mancomunidad_rol CHECK (rol IN ('PROFESOR', 'ADMINISTRADOR')),
    KEY idx_um_mancomunidad_rol (mancomunidad_id, rol, activo),
    KEY idx_um_usuario (usuario_id, activo),
    CONSTRAINT fk_um_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_um_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE refresh_token (
    id BIGINT NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT NOT NULL,
    mancomunidad_id BIGINT NULL,
    scope VARCHAR(20) NOT NULL,
    familia_id CHAR(36) NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    revocado BOOLEAN NOT NULL DEFAULT FALSE,
    revocado_at DATETIME(6) NULL,
    motivo_revocacion VARCHAR(30) NULL,
    reemplazado_por BIGINT NULL,
    ultimo_uso_at DATETIME(6) NULL,
    ip VARCHAR(45) NULL,
    user_agent VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_token_scope CHECK (scope IN ('TENANT', 'PLATFORM')),
    CONSTRAINT ck_refresh_token_motivo CHECK (motivo_revocacion IS NULL OR motivo_revocacion IN ('LOGOUT', 'ROTACION', 'REUTILIZACION', 'CAMBIO_PASSWORD', 'CAMBIO_EMAIL', 'DESACTIVACION', 'CAMBIO_ROL', 'LIMITE_SESIONES')),
    KEY idx_refresh_usuario (usuario_id, revocado, expires_at),
    KEY idx_refresh_mancomunidad (mancomunidad_id, revocado),
    KEY idx_refresh_familia (familia_id, revocado),
    KEY idx_refresh_ultimo_uso (usuario_id, ultimo_uso_at),
    CONSTRAINT fk_refresh_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_refresh_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id),
    CONSTRAINT fk_refresh_reemplazado FOREIGN KEY (reemplazado_por) REFERENCES refresh_token (id) ON DELETE SET NULL
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

