CREATE TABLE sesion_clase (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mancomunidad_id BIGINT NOT NULL,
    curso_escolar_id BIGINT NOT NULL,
    franja_id BIGINT NULL,
    asignatura_id BIGINT NOT NULL,
    profesor_id BIGINT NOT NULL,
    sustitucion_id BIGINT NULL,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    estado VARCHAR(20) NOT NULL,
    observaciones TEXT NULL,
    cancelada_at DATETIME(6) NULL,
    cancelada_por BIGINT NULL,
    motivo_cancelacion VARCHAR(500) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_sesion_franja_fecha UNIQUE (mancomunidad_id, franja_id, fecha),
    CONSTRAINT uq_sesion_puntual UNIQUE (mancomunidad_id, profesor_id, fecha, hora_inicio),
    CONSTRAINT ck_sesion_clase_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_sesion_clase_estado CHECK (estado IN ('PROGRAMADA', 'ABIERTA', 'CERRADA', 'CANCELADA')),
    KEY idx_sesion_asignatura_fecha (mancomunidad_id, asignatura_id, fecha),
    KEY idx_sesion_estado_fecha (mancomunidad_id, estado, fecha),
    KEY idx_sesion_curso (mancomunidad_id, curso_escolar_id),
    CONSTRAINT fk_sesion_clase_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id),
    CONSTRAINT fk_sesion_clase_curso FOREIGN KEY (curso_escolar_id) REFERENCES curso_escolar (id),
    CONSTRAINT fk_sesion_clase_franja FOREIGN KEY (franja_id) REFERENCES franja_horaria (id) ON DELETE SET NULL,
    CONSTRAINT fk_sesion_clase_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignatura (id),
    CONSTRAINT fk_sesion_clase_profesor FOREIGN KEY (profesor_id) REFERENCES usuario (id),
    CONSTRAINT fk_sesion_clase_sustitucion FOREIGN KEY (sustitucion_id) REFERENCES sustitucion (id),
    CONSTRAINT fk_sesion_clase_cancelada FOREIGN KEY (cancelada_por) REFERENCES usuario (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE asistencia (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mancomunidad_id BIGINT NOT NULL,
    sesion_id BIGINT NOT NULL,
    alumno_id BIGINT NOT NULL,
    estado VARCHAR(25) NOT NULL,
    minutos_retraso SMALLINT NULL,
    motivo VARCHAR(255) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_asistencia UNIQUE (mancomunidad_id, sesion_id, alumno_id),
    CONSTRAINT ck_asistencia_estado CHECK (estado IN ('PRESENTE', 'AUSENTE', 'AUSENCIA_JUSTIFICADA', 'RETRASO')),
    CONSTRAINT ck_asistencia_retraso CHECK (minutos_retraso IS NULL OR minutos_retraso BETWEEN 1 AND 180),
    KEY idx_asistencia_alumno (mancomunidad_id, alumno_id),
    KEY idx_asistencia_estado (mancomunidad_id, estado),
    CONSTRAINT fk_asistencia_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id),
    CONSTRAINT fk_asistencia_sesion FOREIGN KEY (sesion_id) REFERENCES sesion_clase (id),
    CONSTRAINT fk_asistencia_alumno FOREIGN KEY (alumno_id) REFERENCES alumno (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE historial_asistencia (
    id BIGINT NOT NULL AUTO_INCREMENT,
