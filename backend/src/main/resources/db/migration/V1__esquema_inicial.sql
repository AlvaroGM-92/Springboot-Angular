CREATE TABLE curso_escolar (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mancomunidad_id BIGINT NOT NULL,
    codigo VARCHAR(9) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    activo_unico BIGINT GENERATED ALWAYS AS (IF(estado = 'ACTIVO', mancomunidad_id, NULL)) STORED,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_curso_escolar UNIQUE (mancomunidad_id, codigo),
    CONSTRAINT uq_curso_escolar_activo UNIQUE (activo_unico),
    CONSTRAINT ck_curso_escolar_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_curso_escolar_estado CHECK (estado IN ('PLANIFICACION', 'ACTIVO', 'CERRADO')),
    CONSTRAINT fk_curso_escolar_mancomunidad FOREIGN KEY (mancomunidad_id) REFERENCES mancomunidad (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

